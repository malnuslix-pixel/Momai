-- 1. ITEMS TABLE (Jobs & Notices published or drafted)
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  k text not null check (k in ('job', 'notice')),
  t text not null,
  who text default '',
  loc text default '',
  cat text default '',
  body text not null,
  st text not null default 'draft' check (st in ('draft', 'published', 'rejected')),
  exp text,
  featured boolean default false,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. SUBMISSIONS TABLE (Incoming form submissions)
create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  ref text unique not null,
  type text not null,
  label text not null,
  from_name text default '',
  title text not null,
  fields jsonb default '[]'::jsonb not null,
  st text not null default 'new' check (st in ('new', 'approved', 'rejected')),
  checks jsonb default '[false, false, false]'::jsonb not null,
  consent boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. SUBSCRIBERS TABLE (Newsletter & WhatsApp channel subscribers)
create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  name text default '',
  consent boolean default true,
  channel text default 'email',
  active boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. ASSISTANT LOGS TABLE ("Ask Mwalimu" queries & answers)
create table if not exists public.assistant_logs (
  id bigint generated by default as identity primary key,
  question text not null,
  reply text,
  model text default 'system',
  status text default 'ok',
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. SITE CONFIG TABLE (Feature flags & emergency banners)
create table if not exists public.site_config (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 6. AUDIT LOG TABLE (Control Room activity records)
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  details jsonb default '{}'::jsonb,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 7. VERIFICATION CHECKS TABLE (Health & syllabus verification status)
create table if not exists public.verification_checks (
  id bigint generated by default as identity primary key,
  name text unique not null,
  last_verified timestamptz,
  status text default 'verified'
);

-- 8. PROFILES TABLE (Linked to Supabase Auth)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  display_name text default '',
  phone text default '',
  role text default 'student' check (role in ('student','parent','teacher','admin')),
  grade text default '',
  school text default '',
  county text default '',
  avatar_url text default '',
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 9. SUBSCRIPTIONS TABLE (M-Pesa subscription plans)
create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  plan text not null check (plan in ('free','premium','pro')),
  status text default 'active' check (status in ('active','cancelled','expired','pending')),
  mpesa_receipt text,
  phone text,
  amount integer default 0,
  started_at timestamptz default timezone('utc'::text, now()),
  expires_at timestamptz,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 10. PAYMENTS TABLE (M-Pesa transaction records)
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  checkout_request_id text unique,
  merchant_request_id text,
  phone text not null,
  amount integer not null,
  plan text not null,
  status text default 'pending' check (status in ('pending','completed','failed','cancelled')),
  mpesa_receipt text,
  result_code integer,
  result_desc text,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 11. TUTOR SESSIONS TABLE (AI Tutor conversation history)
create table if not exists public.tutor_sessions (
  id bigint generated by default as identity primary key,
  session_id text not null,
  user_id uuid references auth.users on delete set null,
  role text not null check (role in ('user','assistant','system')),
  content text not null,
  subject text default '',
  grade text default '',
  mode text default 'chat' check (mode in ('chat','practice','explain')),
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 12. USER XP TABLE (Gamification, streaks, levels)
create table if not exists public.user_xp (
  id uuid references auth.users on delete cascade primary key,
  total_xp integer default 0,
  level integer default 1,
  current_streak integer default 0,
  longest_streak integer default 0,
  last_activity_date date,
  questions_answered integer default 0,
  correct_answers integer default 0,
  tools_used integer default 0,
  sessions_completed integer default 0,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 13. BADGES TABLE
create table if not exists public.badges (
  id text primary key,
  name text not null,
  description text not null,
  icon text not null,
  category text default 'general',
  xp_required integer default 0,
  condition_type text default 'xp',
  condition_value integer default 0,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 14. USER BADGES TABLE
create table if not exists public.user_badges (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  badge_id text references public.badges on delete cascade,
  earned_at timestamptz default timezone('utc'::text, now()) not null,
  unique(user_id, badge_id)
);

