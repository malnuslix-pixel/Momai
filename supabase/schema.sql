-- ==============================================================================
-- MWALIMU FAMILY - SUPABASE DATABASE SCHEMA
-- Full relational schema, row level security (RLS) policies, and seed data
-- ==============================================================================

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. ITEMS TABLE (Jobs & Notices published or drafted)
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  k text not null check (k in ('job', 'notice')),
  t text not null,
  who text default '',
  loc text default '',
  cat text default '',
  body text not null,
  st text not null default 'draft' check (st in ('draft', 'published', 'rejected')),
  exp text,
  featured boolean default false,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 2. SUBMISSIONS TABLE (Incoming form submissions)
create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  ref text unique not null,
  type text not null,
  label text not null,
  from_name text default '',
  title text not null,
  fields jsonb default '[]'::jsonb not null,
  st text not null default 'new' check (st in ('new', 'approved', 'rejected')),
  checks jsonb default '[false, false, false]'::jsonb not null,
  consent boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. SUBSCRIBERS TABLE (Newsletter & WhatsApp channel subscribers)
create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  name text default '',
  consent boolean default true,
  channel text default 'email',
  active boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. ASSISTANT LOGS TABLE ("Ask Mwalimu" queries & answers)
create table if not exists public.assistant_logs (
  id bigint generated by default as identity primary key,
  question text not null,
  reply text,
  model text default 'system',
  status text default 'ok',
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. SITE CONFIG TABLE (Feature flags & emergency banners)
create table if not exists public.site_config (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 6. AUDIT LOG TABLE (Control Room activity records)
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  details jsonb default '{}'::jsonb,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 7. VERIFICATION CHECKS TABLE (Health & syllabus verification status)
create table if not exists public.verification_checks (
  id bigint generated by default as identity primary key,
  name text unique not null,
  last_verified timestamptz,
  status text default 'verified'
);

-- Row Level Security (RLS)
alter table public.items enable row level security;
alter table public.submissions enable row level security;
alter table public.subscribers enable row level security;
alter table public.assistant_logs enable row level security;
alter table public.site_config enable row level security;
alter table public.audit_log enable row level security;
alter table public.verification_checks enable row level security;

-- Public read access for published items
drop policy if exists "Public items are viewable by everyone" on public.items;
create policy "Public items are viewable by everyone"
  on public.items for select
  using (true);

-- Public write access for submissions
drop policy if exists "Anyone can submit forms" on public.submissions;
create policy "Anyone can submit forms"
  on public.submissions for insert
  with check (true);

-- Public select for submissions
drop policy if exists "Admin and readers can view submissions" on public.submissions;
create policy "Admin and readers can view submissions"
  on public.submissions for select
  using (true);

-- Public write access for newsletter
drop policy if exists "Anyone can subscribe" on public.subscribers;
create policy "Anyone can subscribe"
  on public.subscribers for insert
  with check (true);

drop policy if exists "Subscribers viewable" on public.subscribers;
create policy "Subscribers viewable"
  on public.subscribers for select
  using (true);

-- Public read for site_config
drop policy if exists "Public config viewable" on public.site_config;
create policy "Public config viewable"
  on public.site_config for select
  using (true);

-- Service role full access policies
create policy "Service role full access on items" on public.items for all using (true);
create policy "Service role full access on submissions" on public.submissions for all using (true);
create policy "Service role full access on subscribers" on public.subscribers for all using (true);
create policy "Service role full access on assistant_logs" on public.assistant_logs for all using (true);
create policy "Service role full access on site_config" on public.site_config for all using (true);
create policy "Service role full access on audit_log" on public.audit_log for all using (true);
create policy "Service role full access on verification_checks" on public.verification_checks for all using (true);

