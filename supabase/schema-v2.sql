-- 1. USER PROFILES (linked to Supabase Auth)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  display_name text default '',
  phone text default '',
  role text default 'student' check (role in ('student','parent','teacher','admin')),
  grade text default '',
  school text default '',
  county text default '',
  avatar_url text default '',
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null
);

-- 2. SUBSCRIPTIONS (M-Pesa subscription plans)
create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  plan text not null check (plan in ('free','premium','pro')),
  status text default 'active' check (status in ('active','cancelled','expired','pending')),
  mpesa_receipt text,
  phone text,
  amount integer default 0,
  started_at timestamptz default now(),
  expires_at timestamptz,
  created_at timestamptz default now() not null
);

-- 3. PAYMENTS (M-Pesa transaction records)
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  checkout_request_id text unique,
  merchant_request_id text,
  phone text not null,
  amount integer not null,
  plan text not null,
  status text default 'pending' check (status in ('pending','completed','failed','cancelled')),
  mpesa_receipt text,
  result_code integer,
  result_desc text,
  created_at timestamptz default now() not null
);

-- 4. TUTOR SESSIONS (AI Tutor conversation history)
create table if not exists public.tutor_sessions (
  id bigint generated by default as identity primary key,
  session_id text not null,
  user_id uuid references auth.users on delete set null,
  role text not null check (role in ('user','assistant','system')),
  content text not null,
  subject text default '',
  grade text default '',
  mode text default 'chat' check (mode in ('chat','practice','explain')),
  created_at timestamptz default now() not null
);

-- 5. PRACTICE QUESTIONS
create table if not exists public.practice_questions (
  id bigint generated by default as identity primary key,
  subject text not null,
  grade text not null,
  topic text not null,
  question text not null,
  options jsonb default '[]'::jsonb,
  correct_answer text not null,
  explanation text default '',
  difficulty text default 'medium' check (difficulty in ('easy','medium','hard')),
  created_at timestamptz default now() not null
);

-- 6. USER XP (gamification)
create table if not exists public.user_xp (
  id uuid references auth.users on delete cascade primary key,
  total_xp integer default 0,
  level integer default 1,
  current_streak integer default 0,
  longest_streak integer default 0,
  last_activity_date date,
  questions_answered integer default 0,
  correct_answers integer default 0,
  tools_used integer default 0,
  sessions_completed integer default 0,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null
);

-- 7. BADGES
create table if not exists public.badges (
  id text primary key,
  name text not null,
  description text not null,
  icon text not null,
  category text default 'general',
  xp_required integer default 0,
  condition_type text default 'xp',
  condition_value integer default 0,
  created_at timestamptz default now() not null
);

-- 8. USER BADGES
create table if not exists public.user_badges (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  badge_id text references public.badges on delete cascade,
  earned_at timestamptz default now() not null,
  unique(user_id, badge_id)
);

-- 9. LEADERBOARD SNAPSHOTS
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade,
  display_name text,
  county text default '',
  school text default '',
  total_xp integer default 0,
  period text not null,
  period_start date not null,
  rank integer,
  created_at timestamptz default now() not null
);

