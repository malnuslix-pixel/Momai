-- Profiles: users read/update own, public read display_name
create policy "Users can view own profile" on public.profiles for select using (true);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Service role full access on profiles" on public.profiles for all using (true);

-- Subscriptions: users read own
create policy "Users can view own subscriptions" on public.subscriptions for select using (auth.uid() = user_id);
create policy "Service role full access on subscriptions" on public.subscriptions for all using (true);

-- Payments: users read own
create policy "Users can view own payments" on public.payments for select using (auth.uid() = user_id);
create policy "Service role full access on payments" on public.payments for all using (true);

-- Tutor sessions: public insert, users read own
create policy "Anyone can insert tutor messages" on public.tutor_sessions for insert with check (true);
create policy "Users can view own sessions" on public.tutor_sessions for select using (true);
create policy "Service role full access on tutor_sessions" on public.tutor_sessions for all using (true);

-- Practice questions: public read
create policy "Public can view practice questions" on public.practice_questions for select using (true);
create policy "Service role full access on practice_questions" on public.practice_questions for all using (true);

-- User XP: public read (for leaderboard)
create policy "Public can view XP" on public.user_xp for select using (true);
create policy "Service role full access on user_xp" on public.user_xp for all using (true);

-- Badges: public read
create policy "Public can view badges" on public.badges for select using (true);
create policy "Service role full access on badges" on public.badges for all using (true);

-- User badges: public read
create policy "Public can view user badges" on public.user_badges for select using (true);
create policy "Service role full access on user_badges" on public.user_badges for all using (true);

-- Leaderboard: public read
create policy "Public can view leaderboard" on public.leaderboard for select using (true);
create policy "Service role full access on leaderboard" on public.leaderboard for all using (true);

-- ============================================================
-- AUTO-CREATE PROFILE + XP ON USER SIGNUP
-- ============================================================
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', new.email, ''));
  insert into public.user_xp (id)
  values (new.id);
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

